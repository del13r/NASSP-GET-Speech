def list_models(model_dir: str) -> list[str]:
    try:
        return sorted(f for f in os.listdir(model_dir) if f.lower().endswith(".onnx"))
    except OSError:
        return []


class _PathRow(QWidget):
    def __init__(self, value: str, directory: bool = False, filt: str = "", parent=None):
        super().__init__(parent)
        self.directory = directory
        self.filt = filt
        lay = QHBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        self.edit = QLineEdit(value)
        btn = QPushButton("Browse...")
        btn.clicked.connect(self._browse)
        lay.addWidget(self.edit, 1)
        lay.addWidget(btn)

    def _browse(self) -> None:
        start = self.edit.text() or os.path.expanduser("~")
        if self.directory:
            path = QFileDialog.getExistingDirectory(self, "Select folder", start)
        else:
            path, _ = QFileDialog.getOpenFileName(self, "Select file", start, self.filt)
        if path:
            self.edit.setText(os.path.normpath(path))

    def text(self) -> str:
        return self.edit.text().strip()


class SettingsDialog(QDialog):
    def __init__(self, config: Config, parent=None):
        super().__init__(parent)
        self.config = config
        self.setWindowTitle("Settings")
        self.setMinimumWidth(640)
        form = QFormLayout(self)
        self.transcript = _PathRow(config.transcript_file, filt="JSON (*.json);;All files (*)")
        self.models = _PathRow(config.model_dir, directory=True)
        self.piper = _PathRow(config.piper_python, filt="Python (python*.exe);;All files (*)")
        self.wav = _PathRow(config.wav_dir, directory=True)
        self.clear_cache_btn = QPushButton("Clear cache...")
        self.clear_cache_btn.setToolTip("Delete cached audio files generated by NASSP GET Speech")
        self.clear_cache_btn.clicked.connect(self._clear_cache)
        self.wav.layout().addWidget(self.clear_cache_btn)
        self.pipe = QLineEdit(config.pipe_name)
        self.pregen = QDoubleSpinBox()
        self.pregen.setRange(0.5, 30)
        self.pregen.setSuffix(" s")
        self.pregen.setValue(config.pregen_seconds)
        self.grace = QDoubleSpinBox()
        self.grace.setRange(0, 30)
        self.grace.setSuffix(" s")
        self.grace.setValue(config.late_grace_seconds)
        self.max_accel = QDoubleSpinBox()
        self.max_accel.setRange(1, 1000)
        self.max_accel.setSuffix(" x")
        self.max_accel.setValue(config.max_speech_accel)
        form.addRow("Transcript JSON", self.transcript)
        form.addRow("Piper models folder", self.models)
        form.addRow("Python with Piper", self.piper)
        form.addRow("WAV cache folder (blank = default)", self.wav)
        form.addRow("Named pipe", self.pipe)
        form.addRow("Pre-generate ahead", self.pregen)
        form.addRow("Speak late events up to", self.grace)
        form.addRow("Skip crew speech above", self.max_accel)
        buttons = QDialogButtonBox(QDialogButtonBox.Ok | QDialogButtonBox.Cancel)
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        form.addRow(buttons)

    def _target_wav_dir(self) -> str:
        text = self.wav.text()
        if not text:
            return str(config_dir() / "wav")
        return os.path.abspath(text)

    def _clear_cache(self) -> None:
        target_dir = self._target_wav_dir()
        if not os.path.isdir(target_dir):
            QMessageBox.information(
                self,
                "Clear WAV Cache",
                f"WAV cache folder does not exist:\n{target_dir}",
            )
            return

        total_files, total_bytes = scan_wav_cache(target_dir)
        if total_files == 0:
            QMessageBox.information(
                self,
                "Clear WAV Cache",
                f"No cached WAV files found in:\n{target_dir}",
            )
            return

        reply = QMessageBox.question(
            self,
            "Clear WAV Cache",
            f"Found {total_files:,} cached WAV file(s) ({format_size(total_bytes)}) in:\n"
            f"{target_dir}\n\n"
            "Are you sure you want to delete them?\n"
            "Audio will be regenerated automatically when needed.",
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No,
        )
        if reply != QMessageBox.StandardButton.Yes:
            return

        parent = self.parent()
        player = getattr(parent, "player", None)
        if player is not None and hasattr(player, "stop_all"):
            player.stop_all()

        deleted_count, deleted_bytes, failed_count = clear_wav_cache(target_dir)

        if failed_count == 0:
            QMessageBox.information(
                self,
                "WAV Cache Cleared",
                f"Successfully deleted {deleted_count:,} cached WAV file(s) ({format_size(deleted_bytes)}).",
            )
        else:
            QMessageBox.warning(
                self,
                "WAV Cache Partially Cleared",
                f"Deleted {deleted_count:,} cached WAV file(s) ({format_size(deleted_bytes)}).\n\n"
                f"{failed_count} file(s) could not be deleted because they are currently open or locked.",
            )

    def apply_to(self, config: Config) -> None:
        config.transcript_file = self.transcript.text()
        config.model_dir = self.models.text()
        config.piper_python = self.piper.text() or "python"
        config.wav_dir = self.wav.text()
        config.pipe_name = self.pipe.text().strip() or config.pipe_name
        config.pregen_seconds = self.pregen.value()
        config.late_grace_seconds = self.grace.value()
        config.max_speech_accel = self.max_accel.value()


class _VoiceTest(QThread):
    done = Signal(str, str)  # wav path, error

    def __init__(self, config: Config, speaker: str, parent=None):
        super().__init__(parent)
        self.config = config
        self.speaker = speaker
        self.gen = PiperGenerator(config)

    def run(self) -> None:
        try:
            text = f"This is {self.speaker}. Voice check, one two three."
            path = self.gen.generate("test", 0, 0, self.speaker, text)
            self.done.emit(path or "", "")
        except TtsError as exc:
            self.done.emit("", str(exc))

    def cancel(self) -> None:
        self.gen.close()


class VoiceDialog(QDialog):
    """Edit which Piper voice (and channel) each speaker uses."""

    def __init__(self, config: Config, play_callback, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Speaker voices")
        self.setMinimumSize(720, 480)
        self.config = config
        self.play_callback = play_callback
        self._tests: list[_VoiceTest] = []
        work = copy.deepcopy(config.voice_map)
        self.models = list_models(config.model_dir)

        lay = QVBoxLayout(self)
        info = QLabel(
            "Pick a Piper voice for each speaker. Channel sets stereo panning "
            "(crew left / ground right by default) and which side of the chat the speaker appears on."
        )
        info.setObjectName("dim")
        info.setWordWrap(True)
        lay.addWidget(info)
        if not self.models:
            warn = QLabel(f"No .onnx voices found in {config.model_dir!r}. You can still type a model file name.")
            warn.setStyleSheet("color:#ffc857")
            lay.addWidget(warn)

        speakers = list(KNOWN_SPEAKERS) + [s for s in work if s not in KNOWN_SPEAKERS]
        self.table = QTableWidget(len(speakers), 4)
        self.table.setHorizontalHeaderLabels(["Speaker", "Voice model", "Channel", ""])
        self.table.verticalHeader().setVisible(False)
        self.table.verticalHeader().setDefaultSectionSize(54)
        self.table.setIconSize(QSize(40, 40))
        self.table.setSelectionMode(QTableWidget.NoSelection)
        hdr = self.table.horizontalHeader()
        hdr.setSectionResizeMode(0, QHeaderView.ResizeToContents)
        hdr.setSectionResizeMode(1, QHeaderView.Stretch)
        hdr.setSectionResizeMode(2, QHeaderView.ResizeToContents)
        hdr.setSectionResizeMode(3, QHeaderView.ResizeToContents)
        self.model_boxes: dict[str, QComboBox] = {}
        self.pan_boxes: dict[str, QComboBox] = {}
        for r, sp in enumerate(speakers):
            voice = work.get(sp) or config.voice_for(sp)
            item = QTableWidgetItem(sp)
            item.setIcon(QIcon(portrait(sp, sp, 40)))
            item.setFlags(Qt.ItemIsEnabled)
            self.table.setItem(r, 0, item)
            box = QComboBox()
            box.setEditable(True)
            options = list(self.models)
            if voice["model"] and voice["model"] not in options:
                options.insert(0, voice["model"])
            box.addItems(options)
            box.setCurrentText(voice["model"])
            self.table.setCellWidget(r, 1, box)
            self.model_boxes[sp] = box
            pan = QComboBox()
            pan.addItems(PANS)
            pan.setCurrentText(voice.get("pan", "right"))
            self.table.setCellWidget(r, 2, pan)
            self.pan_boxes[sp] = pan
            test = QPushButton("Test")
            test.clicked.connect(lambda _=False, s=sp: self._test(s))
            self.table.setCellWidget(r, 3, test)
        lay.addWidget(self.table, 1)

        self.msg = QLabel("")
        self.msg.setObjectName("dim")
        lay.addWidget(self.msg)
        buttons = QDialogButtonBox(QDialogButtonBox.Save | QDialogButtonBox.Cancel)
        reset = buttons.addButton("Reset to defaults", QDialogButtonBox.ResetRole)
        reset.clicked.connect(self._reset)
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        lay.addWidget(buttons)

    def collect(self) -> dict:
        return {
            sp: {"model": box.currentText().strip(), "pan": self.pan_boxes[sp].currentText()}
            for sp, box in self.model_boxes.items()
        }

    def _reset(self) -> None:
        for sp, v in DEFAULT_VOICES.items():
            if sp in self.model_boxes:
                self.model_boxes[sp].setCurrentText(v["model"])
                self.pan_boxes[sp].setCurrentText(v["pan"])

    def _test(self, speaker: str) -> None:
        cfg = dataclasses.replace(
            self.config,
            voice_map=self.collect(),
            wav_dir=os.path.join(tempfile.gettempdir(), "apollo_voice_test"),
        )
        thread = _VoiceTest(cfg, speaker, self)
        thread.done.connect(self._test_done)
        self._tests.append(thread)
        self.msg.setText(f"Generating test for {speaker}...")
        thread.start()

    def _test_done(self, path: str, err: str) -> None:
        if err:
            self.msg.setText(err)
        elif path:
            self.msg.setText(f"Playing test ({wav_duration(path):.1f}s)")
            self.play_callback(path)

    def done(self, result: int) -> None:
        for t in self._tests:
            t.cancel()
            t.wait(3000)
        super().done(result)
